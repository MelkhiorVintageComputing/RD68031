// RD68031 -- WinUAE's cputest corpus, run on the core.
//
// cputest is a vector set made to be run on real processors: a generator
// (WinUAE's cputestgen, built by tools/cputest/build.sh) writes, for every
// opcode it knows, the starting registers and memory and the registers,
// memory writes and exception it expects, and a small runner on the target
// machine executes each test and compares. tools/cputest/convert.py replays
// that runner's bookkeeping in Python and writes what this bench needs as a
// flat stream -- its format is BENCH_FORMAT in convert.py. This bench is the
// runner, with the core as the target machine:
//
//   - every test is entered the way the runner enters it: an RTE from a frame
//     at SSP-8, with USP = A7, ISP = SSP and MSP as the corpus says;
//   - every test ends in an exception: the ILLEGAL the runner puts after the
//     instruction (the "sentinel", vector 4), or the one the test is about.
//     Every vector points at its own RTE in a table above the test memory,
//     so the program counter says which one was taken, and that RTE is where
//     the next test starts;
//   - at that point the data and address registers, the user stack pointer,
//     the stacked status register (under the corpus's own mask of undefined
//     flags), the stacked PC, the frame's format word and a format $2 frame's
//     address, and every memory write the test was to make, are compared.
//     A long $A/$B bus-fault frame is compared in its first eight bytes only,
//     which is all the corpus records.
//
// The corpus is generated by UAE030's own instruction core; like every oracle
// here it is an ORACLE, not a source, and where it and the core disagree the
// manual decides (doc/m6-mismatches.md, doc/divergences.md).
//
//   +vec=<dir>/cputest.vec   the stream          (default build/cputest/cputest.vec)
//   +mem=<dir>               lmem<N>.hex, tmem<N>.hex (default build/cputest)
//   +faillog=<file>          one line per failing test: id, what, got, expected
//   +maxfail=N               stop after N failures (default 0, never)

`timescale 1ns / 1ps

module core_cputest_tb;

`include "rd68031_core_harness.svh"

  // The corpus lives in the 64 KB 32-bit port (tools/cputest/cputestgen.ini:
  // low memory $0000-$7FFF, test memory $8000-$FFFF). The vector table and the
  // handlers are on the 16-bit port, where no generated address can reach.
  localparam logic [31:0] VBR_TAB   = 32'h1000_0000;
  localparam logic [31:0] HANDLER   = 32'h1000_8000;
  localparam logic [31:0] RESET_SSP = 32'h0000_FF00;
  localparam int          MEMBYTES  = 1 << `TB_S32_ABITS;

  integer      vec, flog;
  string       vecfile, memdir, flogfile, why, lfile, tfile;
  int unsigned kind, n, k, cnt;
  int unsigned id, w0, w1;
  logic [31:0] a, b, c;
  logic [31:0] pc0, sr0, ssp0, msp0;
  logic [31:0] d0 [0:7];
  logic [31:0] a0 [0:7];
  logic [31:0] evec, epc, efmt, naddr, eaddr, skipregs, esr, esrmask;
  logic [31:0] ed [0:7];
  logic [31:0] ea [0:7];
  int unsigned nwr;
  logic [31:0] wr_a [0:63];
  logic [31:0] wr_s [0:63];
  logic [31:0] wr_n [0:63];
  logic [31:0] wr_o [0:63];
  logic [7:0]  boot [0:7];

  int unsigned ntests, passed, failed, shown, maxfail, steps;
  int unsigned f_vec, f_pc, f_fmt, f_sr, f_reg, f_mem, f_hang;
  bit          ok, at_handler, bad;
  logic [31:0] sp, fsr, fpc, ffmt, faddr, gotvec, wantvec, got;

  function automatic logic [31:0] rd8(input logic [31:0] x);
    rd8 = {24'd0, s32.mem[x[`TB_S32_ABITS-1:0]]};
  endfunction
  function automatic logic [31:0] rd16(input logic [31:0] x);
    logic [31:0] x1;
    x1 = x + 1;
    rd16 = {16'd0, s32.mem[x[`TB_S32_ABITS-1:0]], s32.mem[x1[`TB_S32_ABITS-1:0]]};
  endfunction
  function automatic logic [31:0] rd32(input logic [31:0] x);
    logic [31:0] hi, lo;
    hi = rd16(x);
    lo = rd16(x + 2);
    rd32 = {hi[15:0], lo[15:0]};
  endfunction
  task automatic wr8(input logic [31:0] x, input logic [7:0] v);
    s32.mem[x[`TB_S32_ABITS-1:0]] = v;
  endtask
  task automatic wr16(input logic [31:0] x, input logic [15:0] v);
    wr8(x, v[15:8]); wr8(x + 1, v[7:0]);
  endtask
  task automatic wr32(input logic [31:0] x, input logic [31:0] v);
    wr16(x, v[31:16]); wr16(x + 2, v[15:0]);
  endtask

  // The bytes before and after a test, and the stack copy.
  task automatic patches();
    void'($fscanf(vec, "%h", cnt));
    for (k = 0; k < cnt; k = k + 1) begin
      void'($fscanf(vec, "%h %h", a, b));
      wr8(a, b[7:0]);
    end
  endtask

  task automatic copies();
    void'($fscanf(vec, "%h", cnt));
    for (k = 0; k < cnt; k = k + 1) begin
      void'($fscanf(vec, "%h %h %h", a, b, c));
      for (n = 0; n < c; n = n + 1) begin
        got = rd8(a + n);
        wr8(b + n, got[7:0]);
      end
    end
  endtask

  task automatic note(input string what, input logic [31:0] g, input logic [31:0] e);
    if (why == "") $sformat(why, "%s is %08h, the corpus says %08h", what, g, e);
    if (flog != 0) $fdisplay(flog, "%0h %s %08h %08h", id, what, g, e);
  endtask

  // Back to a handler from wherever a test left the core: a reset, with the
  // reset vectors put back for the length of it.
  task automatic recover();
    for (n = 0; n < 8; n = n + 1) begin
      got = rd8(n);
      boot[n] = got[7:0];
    end
    wr32(0, RESET_SSP);
    wr32(4, HANDLER);
    reset_dut();
    run_until(HANDLER, 400, ok);
    for (n = 0; n < 8; n = n + 1) wr8(n, boot[n]);
    if (!ok) begin
      $display("FAIL: core_cputest_tb cannot get the core back to a handler");
      $finish;
    end
  endtask

  initial begin
    if (!$value$plusargs("vec=%s", vecfile)) vecfile = "build/cputest/cputest.vec";
    if (!$value$plusargs("mem=%s", memdir)) memdir = "build/cputest";
    flog = 0;
    if ($value$plusargs("faillog=%s", flogfile)) flog = $fopen(flogfile, "w");
    if (!$value$plusargs("maxfail=%d", maxfail)) maxfail = 0;
    vec = $fopen(vecfile, "r");
    if (vec == 0) begin
      $display("FAIL: core_cputest_tb cannot open %s", vecfile);
      $finish;
    end

    for (n = 0; n < MEMBYTES; n = n + 1) s32.mem[n] = 8'h00;
    // Every vector its own handler, and every handler an RTE: the next test's
    // entry. The NOP after each only pads it to a long word.
    for (n = 0; n < 65536; n = n + 1) s16.mem[n] = 8'h00;
    for (n = 0; n < 256; n = n + 1) begin
      poke_l(VBR_TAB + 4 * n, HANDLER + 4 * n);
      poke_w(HANDLER + 4 * n, 16'h4E73);
      poke_w(HANDLER + 4 * n + 2, 16'h4E71);
    end
    wr32(0, RESET_SSP);
    wr32(4, HANDLER);
    reset_dut();
    run_until(HANDLER, 400, ok);
    if (!ok) begin
      $display("FAIL: core_cputest_tb: the core never reached the first handler");
      $finish;
    end

    ntests = 0; passed = 0; failed = 0; shown = 0;
    f_vec = 0; f_pc = 0; f_fmt = 0; f_sr = 0; f_reg = 0; f_mem = 0; f_hang = 0;
    kind = 0;
    while (kind != 3 && (maxfail == 0 || failed < maxfail)) begin
      if ($fscanf(vec, "%h", kind) != 1) begin
        $display("FAIL: core_cputest_tb: the stream ends without its end record");
        kind = 3;
        failed = failed + 1;
      end
      if (kind == 3) ;
      else if (kind == 2) begin
        void'($fscanf(vec, "%h", k));
        $sformat(lfile, "%s/lmem%0d.hex", memdir, k);
        $sformat(tfile, "%s/tmem%0d.hex", memdir, k);
        $readmemh(lfile, s32.mem);
        $readmemh(tfile, s32.mem);
        patches();
        copies();
        patches();
      end else begin
        patches();
        copies();
        if (kind == 0) begin
          void'($fscanf(vec, "%h %h %h", id, w0, w1));
          void'($fscanf(vec, "%h %h", pc0, sr0));
          for (n = 0; n < 8; n = n + 1) void'($fscanf(vec, "%h", d0[n]));
          for (n = 0; n < 8; n = n + 1) void'($fscanf(vec, "%h", a0[n]));
          void'($fscanf(vec, "%h %h", ssp0, msp0));
          void'($fscanf(vec, "%h %h %h %h %h", evec, epc, efmt, naddr, eaddr));
          void'($fscanf(vec, "%h", skipregs));
          for (n = 0; n < 8; n = n + 1) void'($fscanf(vec, "%h", ed[n]));
          for (n = 0; n < 8; n = n + 1) void'($fscanf(vec, "%h", ea[n]));
          void'($fscanf(vec, "%h %h", esr, esrmask));
          void'($fscanf(vec, "%h", nwr));
          for (n = 0; n < nwr; n = n + 1)
            void'($fscanf(vec, "%h %h %h %h", wr_a[n], wr_s[n], wr_n[n], wr_o[n]));

          // ------------------------------------------------------------
          // In, the runner's way: an RTE from a frame at SSP-8.
          // ------------------------------------------------------------
          wr16(ssp0 - 8, sr0[15:0]);
          wr32(ssp0 - 6, pc0);
          wr16(ssp0 - 2, 16'h0000);
          for (n = 0; n < 8; n = n + 1) dut.u_seq.dreg[n] = d0[n];
          for (n = 0; n < 7; n = n + 1) dut.u_seq.areg[n] = a0[n];
          dut.u_seq.usp_q  = a0[7];
          dut.u_seq.msp_q  = msp0;
          dut.u_seq.isp_q  = ssp0 - 8;
          dut.u_seq.sr_q   = 16'h2700;
          dut.u_seq.vbr_q  = VBR_TAB;
          dut.u_seq.cacr_q = 32'd0;

          // The RTE, the instruction, and whatever follows it, until a vector
          // brings the core back to a handler.
          at_handler = 1'b0;
          ok = 1'b1;
          for (steps = 0; steps < 24 && ok && !at_handler; steps = steps + 1) begin
            step_one(3000, ok);
            at_handler = (steps > 0) && dut.u_ifu.pc_d >= HANDLER
                         && dut.u_ifu.pc_d < HANDLER + 32'h400;
          end
          while (dut.u_biu.post_busy) @(negedge clk);

          ntests = ntests + 1;
          why = "";
          if (!at_handler) begin
            f_hang = f_hang + 1;
            note(ok ? "the instruction count" : "a retirement", dut.u_ifu.pc_d, 32'hFFFF_FFFF);
            $sformat(why, "never reached a handler (the core is at %08h after %0d instructions)",
                     dut.u_ifu.pc_d, steps);
          end else begin
            gotvec  = (dut.u_ifu.pc_d - HANDLER) >> 2;
            wantvec = (evec == 0) ? 32'd4 : evec;
            sp      = dut.u_seq.sr_q[12] ? dut.u_seq.msp_q : dut.u_seq.isp_q;
            fsr     = rd16(sp);
            fpc     = rd32(sp + 2);
            ffmt    = rd16(sp + 6);
            faddr   = rd32(sp + 8);
            bad     = 1'b0;
            if (gotvec !== wantvec) begin
              f_vec = f_vec + 1; bad = 1'b1;
              note("the vector", gotvec, wantvec);
            end else begin
              if (fpc !== epc) begin
                f_pc = f_pc + 1; bad = 1'b1;
                note("the stacked PC", fpc, epc);
              end
              if (evec != 0 && ffmt !== efmt) begin
                f_fmt = f_fmt + 1; bad = 1'b1;
                note("the format word", ffmt, efmt);
              end
              if (evec != 0 && naddr[0] && faddr !== eaddr) begin
                f_fmt = f_fmt + 1; bad = 1'b1;
                note("the frame's address", faddr, eaddr);
              end
              if (((fsr ^ esr) & esrmask) != 32'd0) begin
                f_sr = f_sr + 1; bad = 1'b1;
                note("the stacked SR", fsr, esr);
              end
              if (!skipregs[0]) begin
                for (n = 0; n < 8; n = n + 1)
                  if (dut.u_seq.dreg[n] !== ed[n]) begin
                    if (!bad) f_reg = f_reg + 1;
                    bad = 1'b1;
                    note($sformatf("D%0d", n), dut.u_seq.dreg[n], ed[n]);
                  end
                for (n = 0; n < 7; n = n + 1)
                  if (dut.u_seq.areg[n] !== ea[n]) begin
                    if (!bad) f_reg = f_reg + 1;
                    bad = 1'b1;
                    note($sformatf("A%0d", n), dut.u_seq.areg[n], ea[n]);
                  end
                if (dut.u_seq.usp_q !== ea[7]) begin
                  if (!bad) f_reg = f_reg + 1;
                  bad = 1'b1;
                  note("USP", dut.u_seq.usp_q, ea[7]);
                end
              end
              for (n = 0; n < nwr; n = n + 1) begin
                got = (wr_s[n] == 1) ? rd8(wr_a[n]) : (wr_s[n] == 2) ? rd16(wr_a[n]) : rd32(wr_a[n]);
                if (got !== wr_n[n]) begin
                  if (!bad) f_mem = f_mem + 1;
                  bad = 1'b1;
                  note($sformatf("the %0d-byte write at %08h", wr_s[n], wr_a[n]), got, wr_n[n]);
                end
              end
            end
          end
          if (why == "") passed = passed + 1;
          else begin
            failed = failed + 1;
            if (shown < 25) begin
              shown = shown + 1;
              $display("  FAIL: test %0h (%04h %04h): %s", id, w0[15:0], w1[15:0], why);
            end
          end
          if (!at_handler) recover();
          if ((ntests % 5000) == 0)
            $display("  .. %0d tests, %0d failed", ntests, failed);
        end
        patches();
      end
    end

    $fclose(vec);
    if (flog != 0) $fclose(flog);
    $display("core_cputest_tb: %0d passed, %0d failed, of %0d", passed, failed, ntests);
    $display("core_cputest_tb: failures by first difference -- vector %0d, stacked PC %0d, frame %0d, SR %0d, registers %0d, memory %0d, hung %0d",
             f_vec, f_pc, f_fmt, f_sr, f_reg, f_mem, f_hang);
    if (failed == 0 && ntests != 0) $display("PASS: core_cputest_tb");
    else                             $display("FAIL: core_cputest_tb");
    $finish;
  end

  initial begin
    #1_000_000_000_000;
    $display("FAIL: core_cputest_tb timed out");
    $finish;
  end

endmodule
